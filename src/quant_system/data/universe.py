NIFTY500_SYMBOLS: list[str] = list(dict.fromkeys(NIFTY200_SYMBOLS + NIFTY_SMALLCAP300_SYMBOLS))

UNIVERSE_CATALOG: dict[str, list[str]] = {
    "NIFTY50": NIFTY50_SYMBOLS,
    "NIFTY100": NIFTY100_SYMBOLS,
    "NIFTY200": NIFTY200_SYMBOLS,
    "NIFTY500": NIFTY500_SYMBOLS,
}


def get_universe_symbols(name: str = "NIFTY500") -> list[str]:
    """Returns the constituent symbol list for the requested universe preset."""
    normalized = name.upper().replace(" ", "").replace("-", "").replace("_", "")
    for key, symbols in UNIVERSE_CATALOG.items():
        if key.upper() == normalized or normalized in key.upper():
            return symbols
    return NIFTY500_SYMBOLS
